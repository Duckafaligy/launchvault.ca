"""Writes the Ask LaunchVault library digest: db/supabase/functions/assistant/library.ts (bundled with the Edge Function).
Only READY stories (valid + published by today, same rule as build_app.py). Re-run before every `supabase functions deploy assistant`
so the assistant knows newly published stories:   python scripts/assistant_library.py
"""
import json, os, re, sys
HERE = os.path.dirname(os.path.abspath(__file__)); SITE = os.path.dirname(HERE)
sys.path.insert(0, SITE)
import build_app as B

OUT = os.path.join(os.path.dirname(SITE), "db", "supabase", "functions", "assistant", "library.ts")

def src(f):
    s = f.get("source") or f.get("url") or ""
    return re.sub(r"^https?://(www\.)?", "", s).split("/")[0] if s.startswith("http") else s
def tag(f):
    return "[" + ", ".join(x for x in (f.get("label"), f.get("date"), src(f)) if x) + "]" if f.get("label") else "[not public]"
def txt(c): return c["text"] if isinstance(c, dict) else c

def story(S):
    F = S.get("facts") or {}
    L = [f"## {S['name']} (slug: {S['slug']}) - {S['category']}", f"Link: /app/story/{S['slug']}/",
         f"Title: {S['title']}", f"What: {S['what']}", f"Pattern: {S['pattern']}", "Key numbers:"]
    L += [f"- {n['k']}: {n['v']} {tag(n)}" for n in S["numbers"]]
    for k, lbl in (("first_customers", "First customers"), ("first_revenue", "First money"), ("cost_to_start", "Cost to start"), ("team", "Team")):
        f = F.get(k)
        if isinstance(f, dict): L.append(f"{lbl}: {f.get('text') or 'Not public'} {tag(f)}")
    L.append("Phases:")
    for i, p in enumerate(S["phases"]):
        nums = p.get("number") or []
        nums = nums if isinstance(nums, list) else [nums]
        L.append(f"{i + 1}. {p['name']} ({p['when']}). Lesson: {p['lesson']} What happened: {p['story']}" + "".join(f" Number: {n['v']} {tag(n)}" for n in nums))
    L.append("Founder's moves: " + "; ".join(f"{m['when']}: {m['text']} [{m.get('label', '')}]" for m in S["moves"]))
    L.append("Fact checks:")
    L += [f"- Claim: {f['claim']} -> Found: {f['found']} {tag(f)}" for f in S["fact_checks"]]
    L.append("Checklist (things a member can do this week):")
    L += [f"{i + 1}. {txt(c)}" for i, c in enumerate(S["checklist"])]
    L.append("Sources: " + "; ".join(f"{s['name']} ({s['label']}, {s['date']})" for s in S["sources"]))
    return "\n".join(L)

def main():
    ready = B.load_ready(strict=False)
    body = "\n\n".join(story(S) for S in ready)
    lib = f"LIBRARY: {len(ready)} published LaunchVault breakdowns (generated {B.TODAY}).\n\n{body}"
    slugs = [S["slug"] for S in ready]
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// GENERATED by site/scripts/assistant_library.py from site/data/stories/*.json. Do not edit by hand.\n")
        f.write(f"export const SLUGS: string[] = {json.dumps(slugs)};\n")
        f.write(f"export const LIBRARY: string = {json.dumps(lib, ensure_ascii=False)};\n")
    print(f"assistant library: {len(ready)} stories, {len(lib):,} chars (~{len(lib) // 4:,} tokens) -> {OUT}")

if __name__ == "__main__":
    main()
